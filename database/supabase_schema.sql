-- eChamp S13: tabela para registrar mensagens do formulário de contato.
create table if not exists public.contatos (
  id bigint generated by default as identity primary key,
  nome text not null,
  contato text not null,
  mensagem text not null,
  criado_em timestamptz not null default now()
);

-- Segurança: habilita RLS e permite somente INSERT para visitantes anônimos.
-- Não há política pública de SELECT, UPDATE ou DELETE.
alter table public.contatos enable row level security;

drop policy if exists "Visitantes podem enviar contato" on public.contatos;
create policy "Visitantes podem enviar contato"
on public.contatos
for insert
to anon
with check (
  length(trim(nome)) between 2 and 100
  and length(trim(contato)) between 3 and 150
  and length(trim(mensagem)) between 5 and 2000
);
